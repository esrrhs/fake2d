-- Real interpreted contracts: writes are followed by independent expected values.
function deep_contract(dir, mapfile)
    storage_reset()
    storage_set_num("n", 12.5)
    storage_set_str("s", "hello 世界")
    deep_expect(storage_has("n") and storage_get_num("n", 0) == 12.5, "numeric storage")
    deep_expect(storage_get_str("s", "") == "hello 世界", "UTF8 storage")
    deep_expect(storage_get_num("s", 17) == 17 and storage_get_str("n", "fallback") == "fallback", "typed fallbacks")
    deep_expect(storage_save("lua"), "save JSON")
    storage_reset()
    deep_expect(not storage_has("n") and storage_load("lua") and storage_get_num("n", 0) == 12.5, "JSON reload")
    storage_delete("n")
    deep_expect(not storage_has("n") and not storage_load("../bad") and not storage_save("../bad"), "invalid JSON slots")
    deep_expect(storage_blob_write("lua", dir, "payload", "kind=test", 7), "write blob")
    deep_expect(storage_blob_read("lua", dir) == "payload" and storage_blob_version("lua", dir) == 7, "read blob")
    deep_expect(storage_blob_header("lua", dir) == "kind=test" and storage_blob_size("lua", dir) == 7, "blob metadata")
    deep_expect(not storage_blob_backup_used("lua", dir), "primary chosen")
    deep_expect(storage_blob_read("absent", dir) == "" and storage_blob_version("absent", dir) == 0, "missing blob")
    deep_expect(storage_blob_header("absent", dir) == "" and storage_blob_size("absent", dir) == 0 and not storage_blob_backup_used("absent", dir), "missing metadata")
    deep_expect(storage_slot_name(dir, -1) == "" and storage_slot_name(dir, 999) == "", "slot bounds")
    deep_expect(storage_slot_rename("lua", "lua-renamed", dir), "rename blob")
    deep_expect(storage_blob_read("lua-renamed", dir) == "payload" and storage_slot_delete("lua-renamed", dir), "renamed read and delete")
    deep_expect(storage_slot_count(dir)>0 and storage_slot_name(dir,0)~="", "enumerate existing saves")
    storage_set_str("cross-language", "verified")

    local e = ent_create(42)
    ent_set_tag(e, 9)
    deep_expect(ent_tag(e)==9 and ent_active(e), "entity tag and liveness")
    ent_set_tag(e,42)
    ent_set_num(e, 0, 19.5)
    ent_set_str(e, 0, "entity")
    ent_set_num(e, -1, 99)
    ent_set_str(e, -1, "bad")
    deep_expect(ent_num(e, 0) == 19.5 and ent_str(e, 0) == "entity", "entity values")
    deep_expect(ent_num(e, -1) == 0 and ent_str(e, -1) == "" and ent_at(-1, -1) == 0, "entity negative slots")
    deep_expect(ent_count(-1) == 1 and ent_count(42) == 1 and ent_at(0, 42) == e, "entity enumeration")
    local snapshot = ent_snapshot()
    deep_expect(ent_save("entities", dir), "entity disk save")
    ent_clear()
    deep_expect(ent_count(-1) == 0 and ent_load("entities", dir) and ent_num(ent_at(0, -1), 0) == 19.5, "entity disk restore")
    deep_expect(not ent_load("no-entity", dir) and not ent_restore("broken"), "entity corrupt input")
    ent_clear()
    deep_expect(ent_restore(snapshot) and ent_str(ent_at(0, -1), 0) == "entity", "snapshot restore")
    e = ent_at(0, -1)
    ent_destroy(e)
    deep_expect(ent_count(-1) == 0, "entity teardown")

    local a = anim_create()
    deep_expect(a > 0 and anim_frame_index(a) == -1 and not anim_finished(a), "empty animation")
    anim_frame(a, 0, 0, 0, 8, 8)
    anim_frame(a, 0, 8, 0, 8, 8)
    anim_fps(a, 10)
    anim_loop(a, false)
    anim_play(a)
    deep_step(0.11)
    deep_expect(anim_frame_index(a) == 1 and not anim_finished(a), "advancing clip")
    anim_pause(a)
    deep_step(1)
    deep_expect(anim_frame_index(a) == 1 and not anim_finished(a), "paused clip")
    anim_resume(a)
    deep_step(1)
    deep_expect(anim_finished(a) and anim_frame_index(a) == 1, "nonloop ending")
    anim_stop(a)
    deep_expect(anim_frame_index(a) == 0, "stop rewinds")
    anim_set_frame(a, 99)
    deep_expect(anim_frame_index(a) == 1, "frame clamps")
    anim_destroy(a)
    deep_expect(anim_frame_index(a) == -1 and not anim_finished(a), "destroyed clip")

    local m = map_load(mapfile)
    deep_expect(m > 0 and map_cols(m) == 4 and map_rows(m) == 3 and map_tilew(m) == 8 and map_tileh(m) == 8, "map dimensions")
    deep_expect(map_layer_count(m) == 3 and map_find_layer(m, "objects") == 1, "map layers")
    deep_expect(map_layer_parallax_x(m, 0) == 0.5 and map_layer_parallax_y(m, 0) == 0.75, "layer parallax")
    deep_expect(map_layer_parallax_x(m, -1) == 1 and map_layer_parallax_y(m, 999) == 1, "parallax bounds")
    deep_expect(map_layer_type(m, -1) == -1 and map_obj_count(m, -1) == 0, "layer bounds")
    deep_expect(map_obj_count(m, 1) == 1 and map_obj_id(m, 1, 0) == 7 and map_obj_name(m, 1, 0) == "spawn", "map object identity")
    deep_expect(map_obj_class(m, 1, 0) == "Enemy" and map_obj_x(m, 1, 0) == 12 and map_obj_y(m, 1, 0) == 13, "map object transform")
    deep_expect(map_obj_w(m, 1, 0) == 14 and map_obj_h(m, 1, 0) == 15 and map_obj_rotation(m, 1, 0) == 30 and map_obj_visible(m, 1, 0), "map object geometry")
    deep_expect(map_obj_shape(m, 1, 0) == 4 and map_obj_point_count(m, 1, 0) == 3, "polygon object")
    deep_expect(map_obj_point_x(m, 1, 0, 1) == 16 and map_obj_point_y(m, 1, 0, 1) == 18, "polygon points")
    deep_expect(map_obj_point_x(m, 1, 0, -1) == 0 and map_obj_point_y(m, 1, 0, 99) == 0, "point bounds")
    deep_expect(map_obj_id(m, -1, 0) == 0 and map_obj_class(m, 1, 99) == "" and map_obj_name(m, 99, 0) == "", "object bounds")
    deep_expect(map_obj_has_prop(m, 1, 0, "flag") and map_obj_prop_bool(m, 1, 0, "flag"), "bool property")
    deep_expect(map_obj_prop_num(m, 1, 0, "hp") == 42 and map_obj_prop_str(m, 1, 0, "title") == "boss", "typed object properties")
    deep_expect(not map_obj_has_prop(m, 1, -1, "flag") and map_obj_prop_num(m, 1, -1, "hp") == 0 and map_obj_prop_str(m, 1, -1, "title") == "", "missing object properties")
    deep_expect(map_tile(m, 0, 0) == 1 and map_solid(m, 0, 0) and map_oneway(m, 2, 0), "collision properties")
    map_set_tile(m, 0, 0, 0)
    deep_expect(map_tile(m, 0, 0) == 0 and not map_solid(m, 0, 0), "runtime edit updates collision")
    map_set_tile(0, 0, 0, 1)
    deep_expect(map_anim_count(m, 1) == 2 and map_anim_cycle(m, 1) > 0.29, "tile animation metadata")
    map_anim_reset(m)
    deep_expect(map_anim_index(m, 1) == 0 and map_anim_gid(m, 1) == 1 and map_anim_time(m) == 0, "tile animation reset")
    deep_expect(map_anim_count(m, -1) == 0 and map_anim_cycle(0, 1) == 0 and map_anim_index(m, -1) == -1 and map_anim_gid(0, 1) == 0, "tile animation invalid queries")
    deep_expect(map_path_x(m, -1) == 0 and map_path_y(m, 99) == 0, "path bounds")
    deep_expect(map_flow_build(m, 28, 20, false) and map_flow_has(m) and map_flow_cost(m, 28, 20) == 0, "flow goal")
    deep_expect(map_flow_dir(m, 4, 12) and map_flow_dir_x(m) + map_flow_dir_y(m) > 0, "flow steers toward goal")
    map_flow_clear(m)
    deep_expect(not map_flow_has(m) and not map_flow_has(0), "flow cleanup")

    local p = phys_create_poly(100, 1, -1, -1, 1, -1, 0, 1)
    deep_expect(p ~= 0 and phys_vertex_count(p) == 3 and phys_vertex_x(p, 0) >= 99 and phys_vertex_y(p, 0) >= 0, "convex polygon")
    deep_expect(phys_create_poly(0, 0, 1, 1) == 0, "reject underspecified polygon")
    phys_set_sensor(p, true)
    phys_set_fixed_rot(p, false)
    phys_set_density(p, 2)
    phys_set_friction(p, 0.25)
    phys_set_category(p, 4)
    phys_set_mask(p, 2)
    phys_set_rot(p, 0.5)
    phys_set_ang_vel(p, 0.25)
    deep_expect(phys_mass(p) > 0 and phys_friction(p) == 0.25 and phys_rot(p) == 0.5 and phys_ang_vel(p) == 0.25, "body setters")
    deep_expect(phys_category(p) == 4 and phys_mask(p) == 2, "body filters")
    phys_apply_force(p, 3, 0, 100, 1)
    phys_apply_torque(p, 1)
    phys_wake(p)
    deep_expect(not phys_sleeping(p), "wake")
    phys_set_static(p, true)
    phys_set_static(p, false)
    phys_set_max_substeps(4)
    deep_step(0.01)
    deep_expect(phys_substeps() >= 1, "real physics step")
    local q = phys_create_box(120, 1, 2, 2)
    deep_expect(phys_joint_rope(0, q, 0, 0, 0, 0, 5) == 0, "reject invalid joint body")
    local j = phys_joint_rope(p, q, 100, 1, 120, 1, 25)
    deep_expect(j ~= 0 and phys_joint_count() == 1 and phys_joint_length(j) >= 0, "rope joint")
    phys_joint_destroy(j)
    j = phys_joint_weld(p, q, 100, 1, 120, 1)
    deep_expect(j ~= 0 and phys_joint_count() == 1, "weld joint")
    phys_joint_destroy(j)
    phys_destroy(p)
    phys_destroy(q)
    deep_expect(phys_joint_count() == 0 and phys_friction(p) == 0 and phys_vertex_count(p) == 0, "body cleanup")
    deep_expect(phys_contact_px(-1) == 0 and phys_contact_py(999) == 0 and phys_ray_hit_user() == 0, "empty contacts and ray")

    time_set_scale(0.5)
    deep_expect(time_get_scale() == 0.5, "time scale")
    time_set_scale(-1)
    deep_expect(time_get_scale() == 0, "negative time clamps")
    time_set_scale(1)
    deep_expect(window_width() == 128 and window_height() == 128, "headless dimensions")
    deep_expect(not font_load(dir .. "/missing.ttf", 16) and not font_add_fallback(dir .. "/missing.ttf", 16), "missing fonts rejected")
    deep_expect(font_face_path(999) == "" and text_width("", 1) == 0 and text_line_height() > 0, "font defaults")
    -- Character decoding: ASCII, two/three/four-byte and malformed sequences.
    deep_expect(font_has_glyph("A"), "ASCII glyph")
    deep_expect(font_has_glyph(""), "bitmap ASCII range includes codepoint zero")
    deep_expect(not font_has_glyph("é") and not font_has_glyph("你") and not font_has_glyph("😀"), "bitmap rejects multibyte glyphs")
    deep_expect(i18n_load(dir,"en") and i18n_language_count()==2 and i18n_language()=="en" and not i18n_is_cjk(), "language directory")
    deep_expect(i18n_language_code(0)=="en" and i18n_language_name(0)=="English" and i18n_language_code(99)=="" and i18n_language_name(99)=="", "language metadata bounds")
    deep_expect(i18n_t("你好")=="Hello" and i18n_has("你好") and i18n_entry_count("en")==1, "translation")
    deep_expect(i18n_t_seg("你好，你好！")=="Hello, Hello!", "segmented dictionary and punctuation")
    deep_expect(i18n_format_guard() and i18n_rejected_count()==1 and i18n_rejected_key(0)=="bad %s" and i18n_rejected_key(99)=="", "unsafe translation rejected")
    deep_expect(i18n_format_signature("%03d %.2f %% %ls")=="dfs", "printf signature")
    i18n_set_track_missing(true)
    i18n_clear_missing()
    deep_expect(i18n_t("missing")=="missing" and i18n_missing_count()==1 and i18n_missing_key(0)=="missing" and i18n_missing_key(99)=="", "missing key diagnostics")
    i18n_clear_missing()
    deep_expect(i18n_missing_count()==0, "clear missing")
    i18n_clear_rejected()
    i18n_set_format_guard(false)
    deep_expect(not i18n_format_guard() and i18n_add_file("en",dir .. "/unsafe.dat")==1 and i18n_t("bad %s")=="bad %d" and i18n_rejected_count()==0, "explicit format guard opt-out")
    i18n_set_format_guard(true)
    deep_expect(i18n_set_language("zh") and i18n_is_cjk() and i18n_t("你好")=="你好" and not i18n_set_language("absent"), "language switching")
    mods_clear()
    deep_expect(mods_scan(dir .. "/mods")==1 and mods_count()==1 and mods_active_count()==1 and mods_active_name(0)=="addon", "mod discovery")
    deep_expect(mods_name(0)=="addon" and mods_version(0)=="1.2" and mods_order(0)==7 and mods_enabled(0) and mods_path(0)~="", "mod metadata")
    deep_expect(mods_name(-1)=="" and mods_version(99)=="" and mods_path(99)=="" and mods_order(99)==0 and not mods_enabled(99), "mod bounds")
    deep_expect(mods_set_enabled("addon",false) and mods_active_count()==0 and not mods_set_enabled("absent",true), "mod activation")
    deep_expect(mods_scan_more(dir .. "/no-mods")==1 and mods_load_lang()==0, "empty mod roots and languages")
    mods_base_dir(dir)
    deep_expect(mods_resolve("map.json")~="" and mods_report()~="", "mod resolution and diagnostics")
    mods_clear()
    deep_expect(mods_count()==0, "mod cleanup")
    rng_seed(99)
    local first = rng_float()
    local digest = world_hash()
    rng_float()
    deep_expect(world_hash() ~= digest, "world digest includes RNG state")
    rng_seed(99)
    deep_expect(rng_float()==first and rng_state()~=0, "deterministic RNG round trip")
    deep_expect(rng_range(4,4)==4 and not rng_chance(0) and rng_chance(1), "RNG boundaries")
    deep_expect(lerp(2,10,0.25)==4 and clamp01(-1)==0 and clamp01(2)==1, "interpolation boundaries")
    deep_expect(smoothstep(0,10,0)==0 and approach(2,10,0,1)==2, "stationary easing")
    deep_expect(stats_draw_calls()>0, "stats reflect actual previous render")
    return 321
end
function deep_bad_glyph(text)
    deep_expect(not font_has_glyph(text), "unsupported or malformed first codepoint")
    return 1
end
