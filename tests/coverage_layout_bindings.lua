-- Geometry, tooltip/input conversion and actual render-target pixels are checked.
function layout_contract()
    local red=u_col(1,0,0,1)
    local blue=u_col(0,0,1,1)
    gap_expect(ui_hovered_rect(0,0,10,10),"logical hit test")
    gap_expect(ui_tip_mid_click() and ui_tip_key_lock() and ui_tip_key_esc(),"input edges")
    ui_tip_rect(0,0,10,10,"first")
    gap_expect(ui_tip_poll()=="first","tooltip lookup")
    gap_expect(ui_tip_poll_rect("x")==0 and ui_tip_poll_rect("y")==0 and ui_tip_poll_rect("w")==10 and ui_tip_poll_rect("h")==10 and ui_tip_poll_rect("unknown")==0,"tooltip rect")
    ui_tip_occlude(0,0,10,10)
    gap_expect(ui_tip_poll()=="","tooltip occlusion")
    ui_set_suppress(1)
    gap_expect(not ui_hovered_rect(0,0,10,10),"suppressed input")
    ui_tip_rect(0,0,10,10,"suppressed")
    ui_set_suppress(0)
    ui_root_begin(0,0,60,60,0,false)
    ui_hstack(10,0)
    ui_next_size(20,"auto")
    ui_vstack(0,0)
    ui_remember_box("col-a")
    ui_button("row-a","",1)
    ui_tip("row-tip")
    ui_vstack_end()
    ui_next_size(30,"auto")
    ui_vstack(0,0)
    ui_remember_box("col-b")
    ui_button_ex("styled","",1,true,"test")
    ui_vstack_end()
    ui_hstack_end()
    ui_root_end()
    gap_expect(ui_named("col-a","w")==20,"row first column")
    gap_expect(ui_widget_rect("row-a","w")==20 and ui_widget_rect("row-a","h")>0 and ui_widget_rect("row-a","unknown")==0,"row widget")
    gap_expect(ui_named("col-b","w")==30,"row second column")
    ui_root_begin(0,0,60,60,0,false)
    ui_table_begin("grid",2,2,20,38)
    ui_table_row()
    ui_button("grid-a","",1)
    ui_button("grid-b","",1)
    ui_table_row_end()
    ui_table_end()
    ui_root_end()
    gap_expect(ui_widget_rect("grid-a","x")==0 and ui_widget_rect("grid-a","w")==20,"grid first cell")
    gap_expect(ui_widget_rect("grid-b","x")==22 and ui_widget_rect("grid-b","w")==38,"grid second cell")
    ui_root_begin(0,0,60,60,0,false)
    ui_flow(2,3)
    ui_next_size(25,"auto")
    ui_button("flow-a","",1)
    ui_next_size(40,"auto")
    ui_button("flow-b","",1)
    ui_flow_end()
    ui_root_end()
    gap_expect(ui_widget_rect("flow-b","x")==0 and ui_widget_rect("flow-b","y")>0,"flow wrap")
    ui_root_begin(2,2,20,20,0,false)
    ui_button("anchor","",1)
    ui_remember_box("anchor")
    ui_root_end()
    gap_expect(ui_named("anchor","y")==2 and ui_named("anchor","h")>0 and ui_named("anchor","bad")==0,"remember rect")
    ui_root_begin(24,2,10,10,0,false)
    ui_remember_box("related")
    ui_panel()
    ui_root_end()
    gap_expect(ui_named("related","x")==24,"related geometry")
    gap_expect(ui_named("missing","w")==0,"missing anchor")
    ui_root_begin(0,0,60,60,0,false)
    ui_scroll("scroll",20)
    ui_button("scroll-button","",1)
    ui_tip("scroll-tip")
    ui_scroll_end()
    ui_root_end()
    gap_expect(ui_widget_rect("scroll-button","w")==48,"scroll virtual content and reserved scrollbar")
    gap_expect(ui_tex_ok("sheet.ppm")==1 and ui_tex_ok("missing.png")==0,"texture cache")
    gap_expect(ui_sprite("missing.png",0,0,8,8)==0,"failed sprite")
    ui_quad(0,0,8,8,red)
    gap_expect(ui_sprite("sheet.ppm",16,0,8,8,blue)==1,"tinted sprite")
    ui_frame_screen(40,0,8,8,red,2) -- C++ checks the actual red border pixel.
    ui_root_begin(0,0,64,64,0,false)
    ui_canvas(64,64,0)
    ui_fill_rect(40,20,8,8,red,blue) -- C++ checks fill and expanded border pixels.
    ui_canvas_end()
    ui_root_end()
    ui_tip_rect(0,0,10,10,"covered")
    gap_expect(ui_tip_poll()=="covered","new top tooltip")
    ui_block(0,0,10,10)
    gap_expect(ui_tip_poll()=="","blocked tooltip")
    ui_set_modal(1)
    return 123
end
