-- Geometry, tooltip/input conversion and actual render-target pixels are checked.
function layout_contract()
    local red=u_col(1,0,0,1)
    local blue=u_col(0,0,1,1)
    gap_expect(ui_hovered_rect(0,0,10,10),"logical hit test")
    gap_expect(ui_tip_mid_click() and ui_tip_key_lock() and ui_tip_key_esc(),"input edges")
    ui_tip_rect(0,0,10,10,"first")
    gap_expect(ui_tip_poll()=="first","tooltip lookup")
    gap_expect(ui_tip_poll_rect("x")==0 and ui_tip_poll_rect("y")==0 and ui_tip_poll_rect("w")==10 and ui_tip_poll_rect("h")==10 and ui_tip_poll_rect("unknown")==0,"tooltip rect")
    ui_tip_occlude(0,0,10,10)
    gap_expect(ui_tip_poll()=="","tooltip occlusion")
    ui_set_suppress(1)
    gap_expect(not ui_hovered_rect(0,0,10,10),"suppressed input")
    ui_tip_rect(0,0,10,10,"suppressed")
    ui_set_suppress(0)
    ui_push(0,0,60,60,0)
    ui_row(10,20,30)
    ui_col(0)
    gap_expect(ui_avail_w()==20,"row first column")
    ui_button("row-a",10,"",1)
    gap_expect(ui_last_rect("w")==20 and ui_last_rect("h")==10 and ui_last_rect("unknown")==0,"row widget")
    ui_tip("row-tip")
    ui_col_end()
    ui_col(0)
    gap_expect(ui_avail_w()==30,"row second column")
    ui_button_ex("styled",10,"",1,true,"test")
    ui_col_end()
    ui_row_end()
    ui_pop()
    ui_push(0,0,60,60,0)
    ui_grid_begin(2,2,20,38)
    ui_grid_cell()
    ui_button("grid-a",8,"",1)
    gap_expect(ui_last_rect("x")==0 and ui_last_rect("w")==20,"grid first cell")
    ui_grid_cell_end()
    ui_grid_cell()
    ui_button("grid-b",8,"",1)
    gap_expect(ui_last_rect("x")==22 and ui_last_rect("w")==38,"grid second cell")
    ui_grid_cell_end()
    ui_grid_end()
    ui_pop()
    ui_push(0,0,60,60,0)
    ui_flow_begin(2,3)
    ui_flow_item(25)
    ui_button("flow-a",10,"",1)
    ui_flow_item_end()
    ui_flow_item(40)
    ui_button("flow-b",10,"",1)
    gap_expect(ui_last_rect("x")==0 and ui_last_rect("y")==13,"flow wrap")
    ui_flow_item_end()
    ui_flow_end()
    ui_pop()
    ui_push(2,2,20,20,0)
    ui_button("anchor",10,"",1)
    ui_remember("anchor")
    gap_expect(ui_named("anchor","y")==2 and ui_named("anchor","h")==10 and ui_named("anchor","bad")==0,"remember rect")
    ui_pop()
    gap_expect(ui_push_related("anchor","right",2,10,10,0,0),"related anchor")
    ui_remember_box("related")
    gap_expect(ui_named("related","x")==24,"related geometry")
    ui_pop()
    gap_expect(not ui_push_related("missing","right",2,10,10,0,0),"missing anchor")
    ui_push(0,0,60,60,0)
    ui_scroll_begin("scroll",20)
    gap_expect(ui_avail_w()==48 and ui_avail_h()==0,"scroll virtual content and reserved scrollbar")
    ui_button("scroll-button",10,"",1)
    ui_tip("scroll-tip")
    gap_expect(ui_scroll_end()==10,"measured scroll content height")
    ui_pop()
    gap_expect(ui_tex_ok("sheet.ppm")==1 and ui_tex_ok("missing.png")==0,"texture cache")
    gap_expect(ui_sprite("missing.png",0,0,8,8)==0,"failed sprite")
    ui_quad(0,0,8,8,red)
    gap_expect(ui_sprite("sheet.ppm",16,0,8,8,blue)==1,"tinted sprite")
    ui_frame_screen(40,0,8,8,red,2) -- C++ checks the actual red border pixel.
    ui_push(0,0,64,64,0)
    ui_fill_rect(40,20,8,8,red,blue) -- C++ checks fill and expanded border pixels.
    ui_pop()
    ui_tip_rect(0,0,10,10,"covered")
    gap_expect(ui_tip_poll()=="covered","new top tooltip")
    ui_block(0,0,10,10)
    gap_expect(ui_tip_poll()=="","blocked tooltip")
    ui_set_modal(1)
    return 123
end
