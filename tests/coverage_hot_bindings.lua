-- Additional real interpreter -> engine contracts. No synthetic return mocks.
function hot_contract(dir, mapfile)
    camera_clear_bounds()
    camera_set_position(10,20)
    camera_move(7,3)
    camera_set_zoom(2)
    camera_set_rotation(0.3)
    deep_expect(camera_x()==17 and camera_y()==23 and camera_zoom()==2, "camera move state")
    local wx=camera_screen_to_world_x(43,61)
    local wy=camera_screen_to_world_y(43,61)
    local sx=camera_world_to_screen_x(wx,wy)
    local sy=camera_world_to_screen_y(wx,wy)
    deep_expect(sx>42.99 and sx<43.01 and sy>60.99 and sy<61.01, "camera transformed inverse")
    camera_set_position(0,0)
    camera_set_zoom(1)
    camera_set_rotation(0)
    audio_pause(true)
    deep_expect(audio_paused(), "audio paused state")
    audio_pause(false)
    deep_expect(not audio_paused(), "audio unpaused state")
    audio_bus_set(0,0.25)
    deep_expect(audio_bus_get(0)==0.25, "audio bus round trip")
    audio_bus_set(0,1)
    ach_set_path(dir .. "/hot-achievements.json")
    ach_clear()
    deep_expect(ach_path()==dir .. "/hot-achievements.json" and ach_count()==0, "achievement isolated path")
    deep_expect(ach_unlock("BOSS") and not ach_unlock("BOSS"), "achievement first unlock only")
    deep_expect(ach_unlocked("BOSS") and ach_count()==1 and ach_id(0)=="BOSS", "achievement enumeration")
    deep_expect(not ach_unlocked("absent") and ach_id(900)=="", "achievement bounds")
    ach_clear()
    deep_expect(ach_count()==0 and not ach_unlocked("BOSS"), "achievement clear")
    deep_expect(demo_count()==35 and demo_flag(0)~="" and demo_script(0)~="" and demo_category(0)~="", "demo registry")
    deep_expect(demo_flag(-1)=="" and demo_script(-1)=="" and demo_category(-1)=="", "negative demo index")
    deep_expect(demo_flag(999)=="" and demo_script(999)=="" and demo_category(999)=="", "large demo index")
    deep_expect(not steam_init(0) and not steam_available() and not steam_restart_if_necessary(0), "disabled Steam backend")
    steam_unlock("BOSS")
    steam_rich("state","testing")
    deep_expect(not steam_available(), "disabled Steam writes harmless")
    input_actions_clear("hot-action")
    deep_expect(not input_action_down("hot-action") and not input_action_pressed("hot-action") and not input_action_released("hot-action"), "unbound action")
    deep_expect(not input_pad_down(-1,"a") and not input_pad_released(-1,"a") and input_pad_name(-1)=="", "invalid gamepad")
    local m=map_load(mapfile)
    deep_expect(m>0 and map_slope_rise(m,0,0)==0 and map_slope_rise(0,0,0)==0, "flat and invalid slope")
    deep_expect(map_find_path(m,4,12,28,20,false) and map_path_count(m)>0, "real tile path")
    deep_expect(map_path_x(m,0)==4 and map_path_y(m,0)==12, "path start coordinates")
    deep_expect(not map_find_path(0,4,12,28,20,false) and map_path_count(0)==0 and map_path_y(0,0)==0, "invalid map path")
    map_clear_path(m)
    deep_expect(map_path_count(m)==0, "path lifecycle")
    phys_gravity(0,0)
    local a=phys_create_box(0,0,2,2)
    local b=phys_create_box(3,0,2,2)
    phys_set_user(a,1001)
    phys_set_user(b,1002)
    deep_expect(phys_overlap_box(1.5,0,10,10)==2, "overlap count")
    local first=phys_overlap_id(0)
    local second=phys_overlap_id(1)
    deep_expect((first==a or first==b) and (second==a or second==b) and first~=second, "overlap actual handles")
    deep_expect(phys_overlap_id(-1)==0 and phys_overlap_id(99)==0, "overlap bounds")
    deep_step(0.001)
    deep_expect(phys_contact_count()>0 and phys_contact_px(0)>0 and phys_contact_px(0)<3, "contact world coordinate")
    deep_expect(phys_contact_py(0)>=-2 and phys_contact_py(0)<=2, "contact y coordinate")
    phys_destroy(a)
    phys_destroy(b)
    hot_begin(-100,-100,false)
    deep_expect(ui_begin(), "explicit UI frame")
    ui_push(0,0,128,128,0)
    ui_push(8,12,40,24,0)
    deep_expect(not ui_button("hot-button",10,"Label",1), "idle UI button")
    ui_remember("hot-remember")
    deep_expect(ui_rect("hot-remember","x")==8 and ui_rect("hot-remember","y")==12, "named position")
    deep_expect(ui_rect("hot-remember","w")==40 and ui_rect("hot-remember","h")==10 and ui_rect("hot-remember","bad")==0, "named extent and field bounds")
    ui_pop()
    deep_expect(ui_push_related("hot-remember","left_of",3,5,5), "related left")
    ui_panel()
    deep_expect(ui_last_rect("x")==0, "related left geometry")
    ui_pop()
    deep_expect(ui_push_related("hot-remember","center_x",3,5,5), "related horizontal center")
    ui_panel()
    deep_expect(ui_last_rect("x")==28.5, "related center geometry")
    ui_pop()
    deep_expect(ui_push_related("hot-remember","center_y",3,5,5), "related vertical center")
    ui_panel()
    deep_expect(ui_last_rect("y")==17.5, "related vertical geometry")
    ui_pop()
    deep_expect(not ui_push_related("absent","invalid",0,5,5), "invalid relation rejected")
    deep_expect(ui_push_related("hot-remember","overlay",0,0,0), "overlay relation")
    ui_panel()
    deep_expect(ui_last_rect("x")==8 and ui_last_rect("y")==12 and ui_last_rect("w")==40 and ui_last_rect("h")==10, "overlay inherits target bounds")
    ui_pop()
    deep_expect(ui_push_related("hot-remember","top",3,5,5), "top relation")
    ui_panel()
    deep_expect(ui_last_rect("y")==15, "top offset geometry")
    ui_pop()
    deep_expect(not ui_push_related("hot-remember","invalid",0,5,5), "known target invalid edge rejected")
    deep_expect(not ui_tree("hot-tree",10,"Open",true,1), "tree declaration is deferred")
    ui_pop()
    deep_expect(ui_end() and ui_result("hot-tree",-1)==0 and ui_widget_rect("hot-tree","h")==10, "idle deferred tree resolved without activation")
    deep_expect(ui_widget_rect("hot-button","w")==40 and ui_widget_rect("hot-button","h")==10, "resolved widget extent")
    deep_expect(ui_frame_stat("nodes")>0 and ui_frame_stat("visible")>0 and ui_frame_stat("draw_commands")>0, "actual frame stats")
    deep_expect(ui_frame_stat("tree_steps")>=0 and ui_frame_stat("layout_ms")>=0 and ui_frame_stat("interaction_ms")>=0 and ui_frame_stat("bad")==0, "timing and stat bounds")
    hot_end()
    local oldr=ui_theme_color("panel","r")
    local oldg=ui_theme_color("panel","g")
    local oldb=ui_theme_color("panel","b")
    local olda=ui_theme_color("panel","a")
    deep_expect(ui_set_theme_color("panel",0.125,0.25,0.5,0.75), "set theme")
    deep_expect(ui_theme_color("panel","r")==0.125 and ui_theme_color("panel","g")==0.25 and ui_theme_color("panel","b")==0.5 and ui_theme_color("panel","a")==0.75 and ui_theme_color("panel","bad")==0, "theme channels round trip")
    ui_set_theme_color("panel",oldr,oldg,oldb,olda)
    ui_text_set("hot-text","abc")
    deep_expect(ui_selection("hot-text",false)==3 and ui_selection("hot-text",true)==3, "initial selection")
    deep_expect(not ui_vlist_configure("hot-rows",",a",20) and not ui_vlist_configure("hot-rows","a,",20), "edge empty row IDs rejected")
    deep_expect(not ui_vlist_configure("hot-rows","a,a",20) and not ui_vlist_configure("hot-rows","a,b",0), "duplicate IDs and invalid estimate")
    deep_expect(ui_vlist_configure("hot-rows","a,b,c",20,"v1") and ui_vlist_configure("hot-rows","a,b,c",20,"v1"), "configure is idempotent")
    deep_expect(ui_vlist_total("hot-rows")==60 and not ui_vlist_measured("hot-rows","a"), "unmeasured estimated rows")
    ui_vlist_budget(0)
    deep_expect(ui_vlist_text("hot-rows","b","one two three",1,2), "cache row text")
    hot_begin(-100,-100,false)
    deep_expect(ui_begin(), "variable frame begin")
    ui_push(0,0,128,128,0)
    deep_expect(ui_vlist_begin("hot-rows",60,false), "variable list scope")
    deep_expect(not ui_vlist_configure("hot-rows","changed",20), "active list cannot reconfigure")
    ui_vlist_invalidate("hot-rows")
    local row=ui_vlist_next()
    local seen=0
    while row>=0 do
        deep_expect(ui_vlist_id("hot-rows",row)~="", "row has stable ID")
        ui_text("row",1)
        seen=seen+1
        row=ui_vlist_next()
    end
    deep_expect(seen>0 and seen<=3, "actual visible row iteration")
    ui_vlist_end()
    ui_pop()
    deep_expect(ui_end(), "variable list resolve")
    hot_end()
    deep_expect(ui_vlist_measured("hot-rows","a"), "row measurement side effect")
    ui_vlist_invalidate("hot-rows")
    deep_expect(not ui_vlist_measured("hot-rows","a") and ui_vlist_total("hot-rows")==60, "invalidate restores estimates")
    deep_expect(ui_vlist_next()==-1 and ui_vlist_row_end()==0, "iteration outside scope")
    ui_vlist_end()
    local beforew=ui_last_rect("w")
    local beforeh=ui_last_rect("h")
    -- Out-of-scope controls cannot mutate caller-owned values or invent widgets.
    deep_expect(ui_slider("outside-slider",10,0.375,0,1)==0.375, "unscoped slider preserves value")
    deep_expect(not ui_checkbox("outside-check",10,true,"c") and not ui_radio("outside-radio",10,true,"r"), "unscoped toggles idle")
    deep_expect(not ui_password("outside-password",10) and not ui_text_area("outside-area",10), "unscoped editors idle")
    deep_expect(not ui_combo("outside-combo",10,"c",true) and not ui_combo_item("outside-item",10,"i",true), "unscoped combo controls idle")
    deep_expect(not ui_window("outside-window","w") and not ui_tab("outside-tab",10,"t",true) and not ui_tree("outside-tree",10,"t",true), "unscoped containers idle")
    deep_expect(ui_splitter("outside-splitter",10,37)==37, "unscoped splitter preserves initial value")
    ui_remember("outside-empty")
    deep_expect(ui_rect("outside-empty","w")==beforew and ui_rect("outside-empty","h")==beforeh and ui_widget_rect("outside-slider","w")==0, "unscoped controls preserve last geometry without inventing widgets")
    deep_expect(not ui_push_related("","overlay",0,10,10), "parentless implicit relation rejected")
    deep_expect(ui_push_related("outside-empty","overlay",0,0,0), "named overlay without parent")
    ui_panel()
    deep_expect(ui_last_rect("x")==ui_rect("outside-empty","x") and ui_last_rect("y")==ui_rect("outside-empty","y"), "parentless overlay absolute position")
    ui_pop()
    hot_begin(-100,-100,false)
    ui_push(0,0,120,120,0)
    deep_expect(ui_rich_text("A",1)=="", "idle plain rich text")
    local line=ui_last_rect("h")
    deep_expect(line>0, "rich text baseline line height")
    ui_pop()
    ui_push(0,0,120,120,0)
    deep_expect(ui_rich_text("[color=#11223344]A[/color]",1)=="" and ui_last_rect("h")==line, "RGBA markup has no layout glyphs")
    ui_pop()
    ui_push(0,0,120,120,0)
    deep_expect(ui_rich_text("A\nB",1)=="" and ui_last_rect("h")==2*line, "explicit rich newline doubles height")
    ui_pop()
    ui_push(0,0,8,120,0)
    deep_expect(ui_rich_text("A B C",1)=="" and ui_last_rect("h")>line, "narrow rich text wraps")
    ui_pop()
    ui_push(0,0,120,120,0)
    deep_expect(ui_rich_text("[unknown]",0)=="" and ui_last_rect("h")>0, "unknown markup is literal text using default scale")
    ui_pop()
    ui_push(0,0,0,120,0)
    deep_expect(ui_rich_text("A",1)=="" and ui_last_rect("w")==0 and ui_last_rect("h")==0, "zero-width rich text has empty layout")
    ui_pop()
    local width=text_width("ABC",1)
    deep_expect(draw_text_shadow("ABC",4,3,1,2,2,0,0,0,1,1,1,1,1)==4+width, "text shadow preserves foreground advance")
    deep_expect(draw_text_outline("ABC",4,3,1,1,0,0,0,1,1,1,1,1)==4+width, "text outline preserves foreground advance")
    hot_end()
    font_clear_fallbacks()
    deep_expect(font_face_count()==0 and font_has_glyph("A"), "clearing TTF faces retains the primary bitmap font")
    local target=rt_create(8,8)
    deep_expect(target>0 and rt_valid(target) and rt_active()==0, "offscreen allocation is not binding")
    deep_expect(rt_begin(target) and rt_active()==target, "active target lifecycle")
    rt_clear(1,1,1,1)
    deep_expect(rt_sample(target,0,0)>0.99, "real white framebuffer readback")
    deep_expect(rt_sample(target,-1,0)==-1 and rt_sample(target,8,0)==-1 and rt_sample(-99,0,0)==-1, "invalid samples distinguished from black")
    rt_destroy(target)
    deep_expect(not rt_valid(target) and rt_active()==0 and not rt_begin(target), "destroying active target unbinds and invalidates")
    target=rt_create(8,8)
    deep_expect(rt_resize(target,5,7) and rt_width(target)==5 and rt_height(target)==7, "target resize changes dimensions")
    deep_expect(not rt_resize(-99,5,7) and not rt_resize(target,0,7) and rt_width(target)==5, "invalid resize preserves target")
    rt_destroy(target)
    deep_expect(not rt_valid(target), "resized target released")
    local count=light_count()
    local light=light_create()
    deep_expect(light_valid(light)==1 and light_count()==count+1, "light registration")
    light_destroy(light)
    deep_expect(light_valid(light)==0 and light_count()==count, "light release")
    light_destroy(light)
    deep_expect(light_count()==count, "light release idempotent")
    local blockers=occluder_count()
    local occ=occluder_add_rect(1,2,3,4)
    deep_expect(occ>0 and occluder_count()==blockers+1, "occluder registration")
    occluder_destroy(occ)
    deep_expect(occluder_count()==blockers, "occluder release")
    local root=paths_resource_root()
    paths_set_resource_root(dir)
    deep_expect(paths_resource_root()==dir, "resource-root public setter round trip")
    paths_set_resource_root(root)
    window_set_fullscreen(0)
    deep_expect(not window_fullscreen(), "headless window remains windowed")
    ui_set_page("round7",3)
    deep_expect(ui_page("round7")==3 and ui_theme_metric("spacing")>=0, "page and theme metric getters")
    local sheet=sprite_load(dir .. "/resource-sheet.ppm")
    deep_expect(sheet>0 and sprite_width(sheet)==2, "new texture binding ownership")
    target=rt_create(8,8)
    hot_begin(-100,-100,false)
    deep_expect(rt_begin(target), "nine-slice target bind")
    rt_clear(0,0,0,1)
    draw_nine_slice(sheet,0,0,2,2,0,0,4,4,0.5,0.5,1,0,0,1)
    draw_nine_slice_white(sheet,0,0,2,2,4,4,4,4,0.5,0.5)
    draw_quad_rgb(0,6,2,2,0,1,0)
    rt_end()
    deep_expect(rt_sample(target,1,1)>0.29 and rt_sample(target,1,1)<0.31, "tinted nine-slice really rendered red")
    deep_expect(rt_sample(target,6,6)>0.99 and rt_sample(target,6,1)==0, "white nine-slice extent and untouched background")
    deep_expect(rt_sample(target,1,7)>0.58 and rt_sample(target,1,7)<0.60, "RGB convenience draw really rendered green")
    hot_end()
    rt_destroy(target)
    sprite_free(sheet)
    deep_expect(sprite_width(sheet)==0, "last texture release invalidates handle")
    time_hitstop(0.001)
    return 777
end
