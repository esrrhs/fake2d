-- The same public layout contract is executed through both actual binding hosts.
function ci_ui_layout_contract(full_host)
    local aligns = {"start", "center", "end", "space_between", "space_around", "space_evenly"}
    local first = {0, 50, 100, 0, 25, 100/3}
    local second = {10, 60, 110, 110, 85, 200/3+10}
    for i=1,6 do
        ui_root_begin(0,0,120,40,0,false)
        ui_next_main_align(aligns[i])
        ui_hstack(0,0,"start")
        ui_canvas(10,10) ui_remember_box("axis-a") ui_canvas_end()
        ui_canvas(10,10) ui_remember_box("axis-b") ui_canvas_end()
        ui_hstack_end() ui_root_end()
        deep_expect(math.abs(ui_named("axis-a","x")-first[i])<0.02, "main-axis first "..aligns[i])
        deep_expect(math.abs(ui_named("axis-b","x")-second[i])<0.02, "main-axis second "..aligns[i])
    end
    ui_root_begin(0,0,120,100,0,false)
    ui_next_pad(1,2,3,4) ui_next_margin(2,3,4,5)
    ui_next_shrink(0) ui_next_aspect(2)
    ui_canvas("40","20") ui_remember_box("sized") ui_canvas_end()
    ui_root_end()
    deep_expect(ui_named("sized","w")==40 and ui_named("sized","h")==20, "fixed size strings and aspect")
    deep_expect(ui_named("sized","x")==2 and ui_named("sized","y")==3, "four-sided margin")
    ui_root_begin(0,0,120,100,0,false)
    ui_next_size("50%","grow:2")
    ui_canvas() ui_remember_box("percentage") ui_canvas_end()
    ui_root_end()
    deep_expect(ui_named("percentage","w")==60 and ui_named("percentage","h")==100, "percentage and weighted grow")
    ui_root_begin(0,0,120,100,0,false)
    ui_next_size("fill","grow:0") ui_canvas() ui_remember_box("fill") ui_canvas_end()
    ui_root_end()
    deep_expect(ui_named("fill","w")==120 and ui_named("fill","h")==100, "fill and invalid grow weight fallback")
    ui_root_begin(0,0,120,100,0,false)
    ui_card(2,3) ui_remember_box("card") ui_text("card",1)
    ui_spacer(4) ui_divider() ui_card_end()
    ui_root_end()
    deep_expect(ui_named("card","h")>=12, "auto card contains text padding spacer and divider")
    ui_root_begin(0,0,120,100,0,false)
    ui_table_begin("ci-table",0,0,40,"grow") ui_table_col_limits(0,20,40)
    ui_table_row("baseline")
    ui_cell(2) ui_text("A",1) ui_remember("table-a") ui_cell_end()
    ui_cell() ui_text("B",1) ui_remember("table-b") ui_cell_end()
    ui_table_row_end() ui_table_end() ui_root_end()
    deep_expect(ui_named("table-a","x")==2 and ui_named("table-b","x")==40, "table columns and cell padding")
    ui_root_begin(0,0,120,100,0,false)
    ui_flow(2,3)
    ui_canvas(80,10) ui_remember_box("flow-a") ui_canvas_end()
    ui_canvas(80,10) ui_remember_box("flow-b") ui_canvas_end()
    ui_flow_end() ui_root_end()
    deep_expect(ui_named("flow-b","y")>ui_named("flow-a","y"), "flow wraps oversized sibling")
    ui_root_begin(0,0,120,100,0,false)
    ui_grid_begin(30,2,3,0)
    ui_next_span(2) ui_canvas("grow",10) ui_remember_box("grid-wide") ui_canvas_end()
    ui_canvas("grow",10) ui_remember_box("grid-small") ui_canvas_end()
    ui_grid_end() ui_root_end()
    deep_expect(ui_named("grid-wide","w")>ui_named("grid-small","w"), "grid span consumes multiple columns")
    ui_root_begin(0,0,120,100,0,false)
    ui_zstack()
    ui_canvas(30,20) ui_remember_box("layer-a") ui_canvas_end()
    ui_canvas(10,10) ui_remember_box("layer-b") ui_canvas_end()
    ui_zstack_end() ui_root_end()
    deep_expect(ui_named("layer-a","x")==ui_named("layer-b","x") and ui_named("layer-a","y")==ui_named("layer-b","y"), "z-stack siblings share origin")
    ui_root_begin(0,0,120,100,0,false)
    ui_scroll_xy("ci-scroll",40,60,"both")
    ui_canvas(160,120) ui_canvas_end() ui_scroll_end() ui_root_end()
    deep_expect(ui_scroll_content_w("ci-scroll")>=160, "horizontal content extent")
    if full_host then deep_expect(ui_scroll_content_h("ci-scroll")>=120, "vertical content extent") end
    ui_set_scroll_x("ci-scroll",9999)
    if full_host then ui_set_scroll_offset("ci-scroll",9999) end
    ui_root_begin(0,0,120,100,0,false)
    ui_scroll_xy("ci-scroll",40,60,"xy")
    ui_canvas(160,120) ui_canvas_end() ui_scroll_end() ui_root_end()
    deep_expect(ui_scroll_x("ci-scroll")>0, "horizontal offset clamps to content")
    if full_host then deep_expect(ui_scroll_offset("ci-scroll")>0, "vertical offset clamps to content") end
    ui_root_begin(0,0,120,100,0,false)
    ui_scroll("ci-virtual",40)
    local count=ui_virtual_begin("ci-items",100,10,1)
    deep_expect(count>0 and count<100 and ui_virtual_first()==0, "virtual range bounds")
    for i=1,count do ui_next_height(10) ui_text("row",1) end
    ui_virtual_end() ui_scroll_end() ui_root_end()
    if full_host then deep_expect(ui_scroll_content_h("ci-virtual")>=1000, "virtual unsubmitted rows preserve content height") end
    ui_root_begin(0,0,120,100,0,false)
    ui_push_id("ci-scope") ui_focus_scope_begin("focus",true)
    deep_expect(not ui_btn("scoped","Scoped",1), "scoped button idle")
    ui_focus_scope_end() ui_pop_id()
    ui_next_anim("ci-opacity",0) ui_next_alpha(0.5)
    ui_canvas(10,10) ui_remember_box("animated") ui_canvas_end()
    ui_root_end()
    deep_expect(ui_widget_rect("ci-scope/scoped","w")>0, "scoped identity resolves public widget rectangle")
    deep_expect(ui_named("animated","w")==10, "zero-duration transition preserves target geometry")
    deep_expect(ui_inspector(true), "inspector enables")
    deep_expect(not ui_inspector(false), "inspector disables")
    deep_expect(ui_ime_rect("invalid")==0 and ui_cursor_shape()>=0 and ui_pinch_delta()==0, "idle IME cursor and gesture queries")
    ui_root_begin(0,0,120,100,0,false)
    ui_next_main_align("space_between") ui_hstack(0,0,"start")
    ui_canvas(10,10) ui_remember_box("single") ui_canvas_end()
    ui_hstack_end() ui_root_end()
    deep_expect(ui_named("single","x")==55, "single space-between item is centered")
    ui_root_begin(0,0,120,100,0,false)
    ui_grid_cols_begin(2,2,2,1) ui_next_row_span(2)
    ui_canvas("grow",10) ui_remember_box("fixed-grid") ui_canvas_end()
    ui_grid_end() ui_root_end()
    deep_expect(ui_named("fixed-grid","w")==58, "explicit two-column grid accounts for gap and padding")
    ui_root_begin(0,0,120,100,0,false)
    ui_next_grow(1) ui_next_align("invalid") ui_next_width(20) ui_next_height(20)
    ui_next_radius(0) ui_next_shadow(0,0,0) ui_next_blur(0) ui_next_clip(false)
    ui_next_dir("rtl") ui_next_placeholder("Placeholder") ui_next_tooltip("Help")
    ui_next_semantics("button","Accessible","stable-value","Help")
    if full_host then
        ui_next_bg(1,0,0,1,0) ui_next_border(0,0,1,1,1)
        ui_next_gradient(1,0,0,1,0,1,0,1,true)
    else
        local red=u_col(1,0,0,1) local green=u_col(0,1,0,1)
        ui_next_bg(red,0) ui_next_border(green,1) ui_next_gradient(red,green,true)
    end
    deep_expect(not ui_btn("styled","Styled",1), "styled idle control does not activate")
    ui_root_end()
    deep_expect(ui_widget_rect("styled","w")==20 and ui_widget_rect("styled","h")==20, "styling leaves explicit hit geometry unchanged")
    ui_root_begin(0,0,120,100,0,false)
    if full_host then ui_card(2,2,1,0,0,1,0,0,1,1) else ui_card(2,2,u_col(1,0,0,1),u_col(0,0,1,1)) end
    ui_text("Painted card",1) ui_remember("painted-card") ui_card_end() ui_root_end()
    deep_expect(ui_named("painted-card","h")==8, "colored card preserves child text measure")
    ui_anchor_to("ci-scope/scoped","bottom_start",2,10,10)
    ui_remember_box("bound-anchor") ui_anchor_to_end()
    deep_expect(ui_named("bound-anchor","w")==10 and ui_named("bound-anchor","y")==ui_widget_rect("ci-scope/scoped","y")+ui_widget_rect("ci-scope/scoped","h")+2, "anchored wrapper follows solved widget")
    ui_overlay("center","center",0,0) ui_remember_box("bound-overlay")
    ui_canvas(20,10) ui_canvas_end() ui_overlay_end()
    deep_expect(ui_named("bound-overlay","x")==54 and ui_named("bound-overlay","y")==59, "centered overlay uses intrinsic extent")
    ui_modal_open("ci-modal")
    deep_expect(ui_modal_begin("ci-modal",40,30), "explicitly opened modal builds")
    ui_text("Dialog",1) ui_modal_end() ui_modal_close()
    deep_expect(not ui_modal_begin("ci-modal",40,30), "closed modal does not build")
    deep_expect(ui_inspector(), "inspector toggles on")
    deep_expect(not ui_inspector(), "inspector toggles off")
    if not full_host then
        local old=ui_get_metric("spacing")
        deep_expect(ui_set_metric("spacing",old+1) and ui_get_metric("spacing")==old+1, "theme metric round trip")
        deep_expect(ui_set_metric("spacing",old), "restore theme metric")
        deep_expect(not ui_set_metric("missing-ci-metric",4), "unknown metric rejected")
        ui_root_begin(0,0,120,100,0,false)
        deep_expect(ui_in_auto(), "layout predicate inside root")
        deep_expect(not ui_btn_ex("styled-alias","Alias",1,true,"primary"), "styled alias idle")
        deep_expect(not ui_tab_btn("tab-alias","Tab",true,1), "active tab does not report click")
        ui_pbar(0.5,u_col(0,1,0,1))
        ui_root_end()
        deep_expect(not ui_in_auto(), "layout predicate after root cleanup")
        deep_expect(ui_widget_rect("styled-alias","w")>0 and ui_widget_rect("tab-alias","w")>0, "styled aliases emit geometry")
    end
    local cache_key="ci-cache-standalone"
    if full_host then cache_key="ci-cache-engine" end
    for version=1,2 do
        ui_root_begin(0,0,120,100,0,false)
        deep_expect(ui_cache_begin(cache_key,version), "new subtree version rebuilds")
        ui_canvas(20,10) ui_remember_box("cache-child") ui_canvas_end()
        ui_cache_end() ui_root_end()
        ui_root_begin(10,0,120,100,0,false)
        deep_expect(not ui_cache_begin(cache_key,version), "same subtree version is reused")
        ui_root_end()
        deep_expect(ui_named("cache-child","w")==20, "cached geometry survives replay")
    end
    ui_root_begin(0,0,120,100,0,false)
    deep_expect(not ui_drag_source("drag-source","item","payload"), "idle source is not dragging")
    ui_text("Source",1) ui_drag_source_end()
    deep_expect(not ui_drop_target("drop-target","item"), "idle target does not accept drop")
    ui_text("Target",1) ui_drop_target_end()
    deep_expect(not ui_is_dragging() and ui_drag_type()=="" and ui_drag_payload()=="", "idle drag data is empty")
    deep_expect(not ui_is_drop_hovered("drop-target") and ui_drop_payload("drop-target")=="", "idle drop result is empty")
    deep_expect(not ui_drag_preview(), "no preview without active drag")
    ui_menubar_begin()
    deep_expect(not ui_menu_begin("file-menu","File"), "idle menu closed")
    ui_menubar_end()
    deep_expect(not ui_menu_item("save-item","Save","Ctrl+S",true), "idle menu action not fired")
    ui_menu_separator()
    ui_root_end()
    deep_expect(ui_widget_rect("drag-source","w")>0 and ui_widget_rect("drop-target","w")>0, "drag and drop retain container geometry")
    if not full_host then
        ui_root_begin(0,0,120,100,0,false)
        ui_next_visible(false) ui_next_enabled(false)
        ui_canvas(20,10) ui_remember_box("hidden-bound") ui_canvas_end()
        ui_root_end()
        deep_expect(ui_named("hidden-bound","w")==0 and ui_named("hidden-bound","h")==0, "hidden binding removes layout footprint")
    end
    ui_focus_request("ci-scope/scoped")
    ui_scroll_to("ci-scope/scoped",false)
    ui_focus_clear()
    if full_host then deep_expect(ui_focus()=="", "focus clear removes navigation focus") end
    return 126
end
