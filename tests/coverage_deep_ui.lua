function deep_ui_contract()
    local red = u_col(1,0,0,1)
    local blue = u_col(0,0,1,1)
    deep_expect(ui_measure("ab",32,0)==16, "pixel text measure")
    deep_expect(ui_measure_wrapped("abcd",32,16,0)>8, "wrapped pixel measure")
    deep_expect(ui_text_at(0,110,"ab",32,red,0,0)==16, "pixel text draw width")
    deep_expect(ui_wrapped_at(40,100,16,"abcd",32,red,0)>8, "wrapped pixel draw height")
    deep_expect(not ui_invisible("invisible",0,0,10,10,"tip"), "hover without click")
    deep_expect(ui_tip_poll()=="tip", "invisible widget tooltip")
    ui_tooltip_set("fallback")
    ui_root_begin(0,80,32,"auto",0,false)
    ui_vstack(0,0)
    local wrapped_h = ui_text("abcdefghij",1,"wrap",0,red)
    deep_expect(wrapped_h>8, "text wrapping")
    ui_remember_box("wrapped")
    deep_expect(ui_text("abcdefghij",1,"ellipsis",0,red)==8, "ellipsis height")
    deep_expect(ui_text("abcdefghij",1,"clip",0,red)==8, "clip height")
    local shrunk=ui_text("abcdefghij",1,"shrink",0,red,0.25)
    deep_expect(shrunk>3.19 and shrunk<3.21, "shrink line height")
    deep_expect(ui_text("x")>0, "text optional defaults")
    ui_vstack_end()
    ui_root_end()
    deep_expect(ui_named("wrapped","h")>8, "measured auto height")
    ui_constrain(10,20,10,20)
    ui_root_anchor("left","top",40,40,0,0,0,false)
    ui_panel(red)
    ui_remember_box("constrained")
    ui_root_end()
    deep_expect(ui_named("constrained","w")==20 and ui_named("constrained","h")==20, "constraints and boolean argument")
    ui_root_begin(0,0,100,100,0,false)
    ui_align_begin("aligned","top|height")
    ui_hstack(0,0)
    ui_next_main_align("end")
    ui_next_size(20,"auto")
    ui_vstack(0,0)
    ui_button("align-a","",1)
    ui_vstack_end()
    ui_next_size(20,"auto")
    ui_vstack(0,0)
    ui_button("align-b","",1)
    ui_vstack_end()
    ui_hstack_end()
    ui_align_end()
    ui_disabled_begin(1)
    deep_expect(not ui_checkbox("disabled",true,"",1), "disabled checkbox emits no click")
    deep_expect(not ui_hovered("disabled"), "disabled hover")
    ui_disabled_end()
    deep_expect(ui_slider("slider",5,0,10)==5, "idle slider")
    ui_bar(0.5,red)
    deep_expect(not ui_text_input("empty",0), "unfocused text input")
    ui_root_end()
    ui_root_begin(0,0,32,32,0,false)
    deep_expect(ui_img_box("tiles.ppm",16)==1, "image aspect")
    ui_remember_box("img-box")
    deep_expect(ui_img_box("not-found",16)==0, "missing image")
    ui_root_end()
    deep_expect(ui_named("img-box","h")==16, "image height")
    ui_root_begin(40,0,32,32,0,false)
    ui_panel(red,blue)
    ui_remember_box("bordered-panel")
    ui_root_end()
    deep_expect(ui_named("bordered-panel","w")==32, "bordered panel geometry")
    ui_root_begin(80,0,32,32,0,false)
    ui_panel()
    ui_remember_box("themed-panel")
    ui_root_end()
    deep_expect(ui_named("themed-panel","h")==32, "themed panel geometry")
    ui_root_begin(40,40,32,32,0,false)
    ui_panel(red)
    ui_remember_box("plain-panel")
    ui_root_end()
    deep_expect(ui_named("plain-panel","x")==40, "plain panel geometry")
    return 123
end
function deep_ui_detached()
    deep_expect(not ui_invisible("none",0,0,10,10), "detached invisible")
    deep_expect(ui_measure("ab",16,0)==0 and ui_measure_wrapped("ab",16,10,0)==0, "detached measurements")
    deep_expect(ui_text_at(0,0,"ab",16,0,0,0)==0 and ui_wrapped_at(0,0,10,"ab",16,0,0)==0, "detached draws")
    deep_expect(ui_text("ab")==0 and ui_img_box("tiles.ppm",10)==0, "detached layout")
    deep_expect(ui_slider("none",7,0,10)==7 and ui_checkbox("none",true,"",1), "detached state fallbacks")
    deep_expect(not ui_text_input("none",8) and not ui_hovered("none"), "detached interactions")
    return 124
end
