function deep_ui_contract()
    local red = u_col(1,0,0,1)
    local blue = u_col(0,0,1,1)
    deep_expect(ui_measure("ab",32,0)==16, "pixel text measure")
    deep_expect(ui_measure_wrapped("abcd",32,16,0)>8, "wrapped pixel measure")
    deep_expect(ui_text_at(0,110,"ab",32,red,0,0)==16, "pixel text draw width")
    deep_expect(ui_wrapped_at(40,100,16,"abcd",32,red,0)>8, "wrapped pixel draw height")
    deep_expect(not ui_invisible("invisible",0,0,10,10,"tip"), "hover without click")
    deep_expect(ui_tip_poll()=="tip", "invisible widget tooltip")
    ui_tooltip_set("fallback")
    ui_push(0,80,32,0,0)
    deep_expect(ui_text("abcdefghij",1,"wrap",0,red)>8, "text wrapping")
    ui_record_auto_h("wrapped")
    deep_expect(ui_auto_h("wrapped",-1)==ui_last_rect("h"), "measured auto height")
    deep_expect(ui_text("abcdefghij",1,"ellipsis",0,red)==8, "ellipsis height")
    deep_expect(ui_text("abcdefghij",1,"clip",0,red)==8, "clip height")
    local shrunk=ui_text("abcdefghij",1,"shrink",0,red,0.25)
    deep_expect(shrunk>3.19 and shrunk<3.21, "shrink line height")
    deep_expect(ui_text("x")>0, "text optional defaults")
    ui_pop()
    ui_constrain(10,20,10,20)
    ui_push_anchor("left","top",40,40,0,0,0,false)
    ui_panel(red)
    deep_expect(ui_last_rect("w")==20 and ui_last_rect("h")==20, "constraints and boolean argument")
    ui_pop()
    ui_push(0,0,100,100,0)
    ui_align_begin("aligned","top|height")
    ui_row(0,20,20)
    ui_row_align(2)
    ui_col(0)
    ui_button("align-a",10,"",1)
    ui_col_end()
    ui_col(0)
    ui_button("align-b",10,"",1)
    ui_col_end()
    ui_row_end()
    ui_align_end()
    ui_disabled_begin(1)
    deep_expect(not ui_checkbox("disabled",10,true,"",1), "disabled checkbox emits no click")
    deep_expect(not ui_hovered("disabled"), "disabled hover")
    ui_disabled_end()
    deep_expect(ui_slider("slider",10,5,0,10)==5, "idle slider")
    ui_bar(10,0.5,red)
    deep_expect(not ui_text_input("empty",10,0), "unfocused text input")
    ui_pop()
    ui_push(0,0,32,32,0)
    deep_expect(ui_img_box("tiles.ppm",16)==1 and ui_last_rect("h")==16, "image aspect")
    deep_expect(ui_img_box("not-found",16)==0, "missing image")
    ui_pop()
    ui_push(40,0,32,32,0)
    ui_panel(red,blue)
    deep_expect(ui_last_rect("w")==32, "bordered panel geometry")
    ui_pop()
    ui_push(80,0,32,32,0)
    ui_panel()
    deep_expect(ui_last_rect("h")==32, "themed panel geometry")
    ui_pop()
    ui_push(40,40,32,32,0)
    ui_panel(red)
    deep_expect(ui_last_rect("x")==40, "plain panel geometry")
    ui_pop()
    return 123
end
function deep_ui_detached()
    deep_expect(not ui_invisible("none",0,0,10,10), "detached invisible")
    deep_expect(ui_measure("ab",16,0)==0 and ui_measure_wrapped("ab",16,10,0)==0, "detached measurements")
    deep_expect(ui_text_at(0,0,"ab",16,0,0,0)==0 and ui_wrapped_at(0,0,10,"ab",16,0,0)==0, "detached draws")
    deep_expect(ui_text("ab")==0 and ui_img_box("tiles.ppm",10)==0, "detached layout")
    deep_expect(ui_slider("none",10,7,0,10)==7 and ui_checkbox("none",10,true,"",1), "detached state fallbacks")
    deep_expect(not ui_text_input("none",10,8) and not ui_hovered("none"), "detached interactions")
    return 124
end
