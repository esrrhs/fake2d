-- Assert C++/Lua conversion, lookup, animation state, invalid IDs and cleanup.
function binding_roundtrip(path, mesh_path)
    local a=skel_load(path)
    gap_expect(a>0 and skel_asset_valid(a),"load asset")
    gap_expect(skel_clip_exists(a,"turn") and not skel_clip_exists(a,"absent"),"clip lookup")
    local s=skel_create(a)
    gap_expect(s>0 and skel_valid(s) and skel_count()==1,"create instance")
    gap_expect(skel_play(s,"turn",0) and skel_playing(s),"play")
    gap_expect(skel_clip_count(s)==1 and skel_clip_index(s)==1,"clip index")
    gap_expect(skel_clip_name(s)=="turn" and skel_clip_name_at(s,1)=="turn","clip names")
    gap_expect(skel_clip_name_at(s,0)=="" and skel_clip_name_at(s,99)=="","clip bounds")
    skel_pause(s)
    gap_expect(not skel_playing(s),"pause")
    skel_resume(s)
    gap_expect(skel_playing(s),"resume")
    skel_set_speed(s,-2)
    gap_expect(skel_speed(s)==-2,"speed")
    skel_set_time(s,0.5)
    gap_expect(skel_time(s)==0.5 and skel_duration(s)==1,"clock")
    gap_expect(skel_bone_rot(s,0)>44 and skel_bone_rot(s,0)<46,"sampled rotation")
    skel_set_weight(s,0)
    gap_expect(skel_weight(s)==0 and skel_bone_rot(s,0)==0,"pose weight")
    skel_set_weight(s,1)
    skel_set_mix(s,0.2)
    gap_expect(skel_set_clip(s,"turn") and skel_play_index(s,1,0),"indexed play")
    skel_set_time(s,0) -- Play changes the clock; explicit seeking samples immediately.
    gap_expect(skel_bone_count(s)==2 and skel_bone_index(s,"tip")==1,"bone lookup")
    gap_expect(skel_bone_name(s,1)=="tip" and skel_bone_parent(s,1)==0,"bone hierarchy")
    gap_expect(skel_bone_x(s,1)==10 and skel_bone_y(s,1)==0 and skel_bone_length(s,0)==10,"bone pose")
    gap_expect(skel_set_bone(s,"tip",20,5,0,1,1),"set bone")
    gap_expect(skel_bone_x(s,1)==20 and skel_bone_y(s,1)==5,"changed bone")
    gap_expect(skel_reset_bone(s,"tip") and skel_bone_x(s,1)==10,"reset bone")
    skel_reset_pose(s)
    gap_expect(skel_aim(s,"root",0,20) and skel_bone_rot(s,0)>89,"aim")
    gap_expect(not skel_ik(s,"root","tip","missing",0,0,1),"invalid IK")
    gap_expect(skel_slot_count(s)==1 and skel_slot_index(s,"body")==0 and skel_slot_name(s,0)=="body","slot lookup")
    gap_expect(skel_slot_color(s,"body",1,0.5,0,1) and skel_slot_attach(s,"body","art"),"slot mutation")
    gap_expect(skel_slot_visible(s,"body",false) and skel_bounds_w(s)==0,"hidden bounds")
    gap_expect(skel_slot_visible(s,"body",true) and skel_bounds_w(s)>9 and skel_bounds_h(s)>9,"visible bounds")
    gap_expect(skel_skin(s,"missing")==0 and not skel_finished(s),"skin and finish")
    gap_expect(not skel_mesh(s,0) and skel_mesh_vertex_count(s,0)==0,"region not mesh")
    gap_expect(skel_event_count(s)==0 and skel_event_name(s,1)=="" and skel_event_data(s,1)==0,"empty events")
    local ma=skel_load(mesh_path)
    local m=skel_create(ma)
    gap_expect(skel_mesh(m,0) and skel_mesh_vertex_count(m,0)==3 and skel_mesh_triangle_count(m,0)==1,"mesh topology")
    gap_expect(skel_mesh_bind_x(m,0,1)==10 and skel_mesh_bind_y(m,0,2)==10,"bind geometry")
    gap_expect(skel_mesh_x(m,0,1)==10 and skel_mesh_y(m,0,2)==10,"world geometry")
    gap_expect(skel_mesh_weight_count(m,0,0)==0 and skel_mesh_weight_bone(m,0,0,0)==-1 and skel_mesh_weight(m,0,0,0)==0,"rigid mesh weights")
    gap_expect(skel_hull_count(m,0)==3 and skel_hull_x(m,0,1)==10 and skel_hull_y(m,0,2)==10,"mesh hull")
    gap_expect(not skel_mesh_deform(m,0,0),"no authored deform")
    gap_expect(not skel_asset_valid(-1) and not skel_valid(-1),"invalid ownership")
    gap_expect(skel_create(-1)==0 and not skel_play(-1,"turn",0),"invalid create play")
    gap_expect(skel_bone_name(-1,0)=="" and skel_slot_name(-1,0)=="","invalid names")
    gap_expect(skel_mesh_x(-1,0,0)==0 and skel_mesh_y(-1,0,0)==0,"invalid mesh world")
    gap_expect(skel_hull_x(-1,0,0)==0 and skel_hull_y(-1,0,0)==0,"invalid hull")
    gap_expect(skel_bounds_x(-1)==0 and skel_bounds_y(-1)==0 and skel_bounds_w(-1)==0 and skel_bounds_h(-1)==0,"invalid bounds")
    skel_destroy(s)
    gap_expect(not skel_valid(s) and skel_count()==1,"destroy instance")
    skel_asset_destroy(ma)
    gap_expect(not skel_valid(m) and not skel_asset_valid(ma) and skel_count()==0,"asset cascade")
    skel_asset_destroy(a)
    gap_expect(not skel_asset_valid(a),"release asset")
    return 123
end
